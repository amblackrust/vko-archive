import { expect, test, type Page } from "@playwright/test";
import { DEMO_CODES, documentId, publicApi } from "./helpers";

// Живая Ollama нужна только этим тестам; без неё они пропускаются (мягкая проверка).
test.beforeAll(async () => {
  const api = await publicApi();
  const status = await api.get("/api/ai/status");
  const available = status.ok() && (await status.json()).ai_available === true;
  await api.dispose();
  test.skip(!available, "Ollama недоступна: ИИ-сценарии пропущены");
});

const SEARCH_TIMEOUT = 120_000;

async function ask(page: Page, locale: string, q: string) {
  await page.goto(`/${locale}/search?q=${encodeURIComponent(q)}`);
  await expect(page.getByText(/Сформировано ИИ|ЖИ жасаған|Generated by AI|AI-generated|не нашёл|не могу|не выполнялся|Ничего не найдено|Поиск по этому запросу/i).first()).toBeVisible({
    timeout: SEARCH_TIMEOUT,
  });
}

async function sourceIds(page: Page) {
  const hrefs = await page.locator('main a[href*="/catalog/documents/"]').evaluateAll((els) => els.map((e) => e.getAttribute("href") ?? ""));
  return [...new Set(hrefs.map((h) => h.split("/").pop()!))];
}

test.describe("Сценарий 2. Интеллектуальный поиск", () => {
  test.setTimeout(SEARCH_TIMEOUT + 30_000);
  // Локальная модель недетерминирована (иногда отвечает «не нашёл» на рабочий запрос): допускаем повтор.
  test.describe.configure({ retries: 2 });

  test("запрос обычным языком: чипы фильтров, реальные записи, ссылки строит сервер", async ({ page }) => {
    await ask(page, "ru", "фото цеха 1950-х");
    await expect(page.getByText("ИИ-справка")).toBeVisible();
    await expect(page.getByText("Сформировано ИИ, не является архивной справкой").first()).toBeVisible();
    // Чипы фильтров, разобранные из запроса.
    await expect(page.getByRole("button", { name: /Убрать фильтр: Тип: Фотография/ })).toBeVisible();
    await expect(page.getByRole("button", { name: /Убрать фильтр: Период: 1950-е/ })).toBeVisible();

    const ids = await sourceIds(page);
    expect(ids.length).toBeGreaterThan(0);
    const api = await publicApi();
    for (const id of ids) {
      const card = await api.get(`/api/catalog/documents/${id}`);
      expect(card.status(), `источник ${id} должен существовать`).toBe(200);
      expect((await card.json()).is_demo).toBe(true);
    }
    await api.dispose();
  });

  test("тот же запрос на казахском языке", async ({ page }) => {
    await ask(page, "kk", "1950 жылдардағы цех фотосуреттері");
    await expect(page).toHaveURL(/\/kk\/search/);
    await expect(page.locator("html")).toHaveAttribute("lang", "kk");
    await expect(page.getByText(/Application error|Internal Server Error/)).toHaveCount(0);
  });

  test("негатив: нет в архиве - не выдумывает документы", async ({ page }) => {
    await ask(page, "ru", "метро в Усть-Каменогорске");
    expect(await sourceIds(page)).toEqual([]);
    await expect(page.getByText("ИИ-справка")).toBeVisible();
  });

  test("негатив: посторонняя просьба - отказ без источников", async ({ page }) => {
    await ask(page, "ru", "напиши код на python для сортировки");
    expect(await sourceIds(page)).toEqual([]);
    await expect(page.getByText(/помочь не могу|не могу помочь|только по архиву/i).first()).toBeVisible({ timeout: SEARCH_TIMEOUT });
  });

  test("вопрос по документу: ответ ИИ с пометкой", async ({ page }) => {
    await page.goto(`/ru/catalog/documents/${await documentId(DEMO_CODES.order31)}`);
    await page.getByRole("button", { name: "Когда выдан документ?" }).click();
    await expect(page.getByText("Сформировано ИИ, не является архивной справкой")).toBeVisible({ timeout: SEARCH_TIMEOUT });
  });
});
