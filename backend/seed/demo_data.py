"""T2.3: data of the demo catalog. Everything here is FICTITIOUS (is_demo=True): people,
organisations' internal documents, dates and texts are invented for the prototype.
Real places and historical periods are used only as a backdrop."""

from dataclasses import dataclass, field


@dataclass
class Doc:
    title: str
    doc_type: str  # order / protocol / decision / photo / drawing / map / letter / newspaper / certificate / personal / manuscript / audio / video / ...
    date_text: str
    date_from: str  # ISO date
    date_to: str | None = None
    summary: str = ""
    authors: str = ""
    place: str = "Усть-Каменогорск"
    topics: tuple[str, ...] = ()
    desc: str = "public"  # description_status
    access: str = "open"  # file_access
    conditions: str | None = None
    kind: str | None = "scan"  # scan / photo / audio / None (no digital copy)
    pages: tuple[str, ...] = ()  # page texts of the scan; they double as the simulated OCR text
    sheets: int = 1
    note: str = ""


@dataclass
class DemoCase:
    number: str
    title: str
    docs: list[Doc]


@dataclass
class DemoInventory:
    number: str
    title: str
    cases: list[DemoCase]


@dataclass
class DemoFund:
    number: str
    type: str
    title: str
    year_from: int
    year_to: int
    annotation: str
    inventories: list[DemoInventory] = field(default_factory=list)


