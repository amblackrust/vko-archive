def seed_news(session: Session, report: Report, refresh: bool) -> None:
    for slug, category, title, summary, published_at, body in NEWS:
        upsert(
            session, report, News, {"slug": slug},
            {
                "category": category,
                "title": i18n(ru=title),
                "summary": i18n(ru=summary),
                "body": i18n(ru=body),
                "published_at": published_at,
                "is_demo": True,
                "workflow_status": PUBLISHED,
                "translation_status": dict(NO_TRANSLATION),
            },
            refresh,
        )  # fmt: skip


def seed_faq(session: Session, report: Report, refresh: bool) -> None:
    for topic, pairs in FAQ_TOPICS:
        for position, (question, answer) in enumerate(pairs, 1):
            upsert(
                session, report, FAQ, {"slug": f"faq-{topic}-{position}"},
                {
                    "category": topic,
                    "position": position,
                    "question": i18n(ru=question),
                    "answer": i18n(ru=answer),
                    "workflow_status": PUBLISHED,
                    "translation_status": dict(NO_TRANSLATION),
                },
                refresh,
            )  # fmt: skip
